def build_and_validate_reference_dataset() -> pd.DataFrame:
    """Builds, rigorously validates, and exports the verified USDA food dataset."""
    validated_rows = []
    
    for food in VERIFIED_FOODS:
        # Schema validation
        schema_obj = FoodItemSchema(**food)
        
        # Physical consistency check
        atwater = validate_atwater_balance(
            schema_obj.protein_per_100g,
            schema_obj.carbs_per_100g,
            schema_obj.fat_per_100g,
            schema_obj.calories_per_100g
        )
        if not atwater["is_physically_consistent"] and schema_obj.calories_per_100g > 10.0:
            print(f"Warning: Atwater discrepancy on {schema_obj.name}: {atwater}")

        # Serialized dictionary
        d = schema_obj.model_dump()
        d["allergens"] = ",".join(d["allergens"]) if d["allergens"] else "None"
        d["suitable_meals"] = ",".join(d["suitable_meals"])
        validated_rows.append(d)
        
    df = pd.DataFrame(validated_rows)
    target_path = REFERENCE_DATA_DIR / "verified_food_composition.csv"
    df.to_csv(target_path, index=False)
    print(f"Successfully generated and validated {len(df)} records at {target_path}")
    return df


if __name__ == "__main__":
    build_and_validate_reference_dataset()
