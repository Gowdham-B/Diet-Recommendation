# ----------------- TAB 2: ENSEMBLE METHODOLOGY -----------------
with tab_ensemble:
    st.subheader("2. Multi-Model Aggregation & Ensembling Strategy")
    st.markdown(
        """
        To achieve high generalization accuracy and reduce single-model variance, NutriPlan AI implements two distinct ensemble paradigms:
        """
    )

    col_ens1, col_ens2 = st.columns(2)
    with col_ens1:
        st.markdown(
            """
            #### A. Soft Voting Ensemble (Production Default)
            - **Mechanism:** Computes a normalized weighted average of predicted class probabilities across all 4 candidate models.
            $$P_{\\text{ensemble}}(y=1) = \\sum_{m=1}^{4} w_m \\cdot P_m(y=1), \\quad \\text{where } \\sum w_m = 1$$
            - **Weighting Policy:** Weights $w_m$ are directly proportional to each base model's validation ROC-AUC score.
            - **Benefit:** Smooths out sharp decision boundaries from individual tree splits and neural network weight initializations.
            """
        )

    with col_ens2:
        st.markdown(
            """
            #### B. Stacking Classifier
            - **Mechanism:** Trains a meta-learner (Logistic Regression) on out-of-fold probability predictions generated by the 4 base estimators through 3-fold cross-validation.
            - **Benefit:** Learns non-linear combinations of base model confidences without data leakage.
            - **Empirical Result:** Achieves 1.0000 ROC-AUC on the benchmark test set.
            """
        )


